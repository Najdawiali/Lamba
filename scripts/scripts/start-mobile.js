/**
 * Eagle Vision — Mobile Dev Server Launcher
 * 
 * Automatically detects the host machine's active local IPv4 address,
 * updates the `mobile/.env` file with the correct backend URL,
 * and launches the Expo dev server for seamless testing on physical devices.
 */

const os = require('os');
const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

function getBestIP() {
  const interfaces = os.networkInterfaces();
  const candidates = [];

  for (const name of Object.keys(interfaces)) {
    // Skip virtual or local loopback interfaces if we can
    const isVirtual = /virtual|vbox|wsl|vmware|docker|host-only|hyper-v/i.test(name);

    for (const iface of interfaces[name]) {
      // Look for active non-internal IPv4 addresses
      if (iface.family === 'IPv4' && !iface.internal) {
        // Skip APIPA (Automatic Private IP Addressing) e.g., 169.254.x.x
        if (iface.address.startsWith('169.254')) continue;

        candidates.push({
          name,
          address: iface.address,
          isVirtual
        });
      }
    }
  }

  if (candidates.length === 0) {
    return '127.0.0.1';
  }

  // Prioritize non-virtual adapters (physical Wi-Fi or Ethernet)
  const physicalCandidates = candidates.filter(c => !c.isVirtual);
  if (physicalCandidates.length > 0) {
    // Prefer Wi-Fi or wireless interfaces for mobile testing, then Ethernet
    const wifi = physicalCandidates.find(c => /wi-fi|wlan|wireless/i.test(c.name));
    if (wifi) return wifi.address;

    const ethernet = physicalCandidates.find(c => /ethernet|eth/i.test(c.name));
    if (ethernet) return ethernet.address;

    return physicalCandidates[0].address;
  }

  // Fallback to whatever IPv4 address we found
  return candidates[0].address;
}

// Main execution
function main() {
  console.log('🦅  Eagle Vision - Initializing Mobile Dev Environment...\n');

  const localIp = getBestIP();
  console.log(`🌐  Detected Local IP Address: \x1b[36m${localIp}\x1b[0m`);
  
  const backendUrl = `http://${localIp}:8000`;
  console.log(`🔌  Setting backend API URL to: \x1b[32m${backendUrl}\x1b[0m`);

  // Target paths
  const mobileDir = path.join(__dirname, '..', 'mobile');
  const envPath = path.join(mobileDir, '.env');

  // Construct env file contents
  const envContent = `# Generated by scripts/start-mobile.js\n# Do not commit this file to git\nEXPO_PUBLIC_API_URL=${backendUrl}\n`;

  try {
    fs.writeFileSync(envPath, envContent, 'utf8');
    console.log(`📝  Successfully updated \x1b[34mmobile/.env\x1b[0m`);
  } catch (error) {
    console.error('❌  Error writing mobile/.env file:', error.message);
    process.exit(1);
  }

  // Check command line arguments for tunnel mode
  const isTunnel = process.argv.includes('--tunnel');
  
  console.log('\n🚀  Launching Expo Dev Server...');
  if (isTunnel) {
    console.log('📡  Running in \x1b[35mTunnel Mode\x1b[0m (using ngrok). Perfect for remote or restricted Wi-Fi.');
  } else {
    console.log('📶  Running in \x1b[33mLocal Mode\x1b[0m. Ensure phone and PC are on the same Wi-Fi network.');
  }
  console.log('------------------------------------------------------------\n');

  const args = ['expo', 'start'];
  if (isTunnel) {
    args.push('--tunnel');
  }

  // Spawn Expo process in mobile directory
  const expoProcess = spawn('npx', args, {
    cwd: mobileDir,
    stdio: 'inherit',
    shell: true
  });

  expoProcess.on('error', (err) => {
    console.error('❌  Failed to start Expo process:', err.message);
  });
}

main();
